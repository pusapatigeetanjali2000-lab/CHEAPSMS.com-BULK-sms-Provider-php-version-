document.addEventListener("DOMContentLoaded", function () {
  const header = document.getElementById("siteHeader");
  const hamburger = document.getElementById("hamburger"); // Targets your hamburger button if present

  let lastScrollTop = 0;
  const deltaSensitivity = 8; // Pixels to scroll before triggering header reveal/hide
  
  // Calculate header height automatically to set dynamic buffer space on pages
  const headerHeight = header.offsetHeight;
  document.body.style.paddingTop = headerHeight + "px";

  window.addEventListener("scroll", function () {
    let currentScroll = window.pageYOffset || document.documentElement.scrollTop;

    // Stop script handling if user bounces at extreme top/bottom (safeguard for iOS)
    if (currentScroll < 0) return;

    // Safety: If the mobile navigation overlay is wide open, don't hide the header
    if (hamburger && hamburger.classList.contains("is-active")) {
      lastScrollTop = currentScroll;
      return;
    }

    // Ignore minor, accidental micro-scroll tremors
    if (Math.abs(currentScroll - lastScrollTop) <= deltaSensitivity) return;

    if (currentScroll > lastScrollTop && currentScroll > headerHeight) {
      // Scrolling Down: Push header away out of frame
      header.classList.remove("scroll-up");
      header.classList.add("scroll-down");
    } else if (currentScroll < lastScrollTop) {
      // Scrolling Up: Immediately drop navigation back down
      header.classList.remove("scroll-down");
      header.classList.add("scroll-up");
    }

    lastScrollTop = currentScroll;
  }, { passive: true });
});
</script>
